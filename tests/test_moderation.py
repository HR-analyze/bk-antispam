@pytest.mark.parametrize("text,expected", SPAM_CASES)
def test_spam_is_flagged(text, expected):
    assert classify_message(text) == expected


@pytest.mark.parametrize("text", CLEAN_CASES)
def test_clean_messages_survive(text):
    assert classify_message(text) is None


def test_every_verdict_has_a_label():
    """Ключи классификатора должны существовать в REASONS.

    Иначе delete_reason уезжает в БД как NULL, а дашборд получает метку,
    которую не знает.
    """
    verdicts = {expected for _, expected in SPAM_CASES} | {"flood"}
    assert verdicts <= set(REASONS), verdicts - set(REASONS)


def test_link_from_telegram_entities():
    """Ссылка без схемы приходит из entities, а не из текста."""
    assert classify_message("тут всё", has_link=True) == "link"
    assert classify_message("тут всё", has_link=False) is None
